    """
    Manages the full subagent lifecycle:
      spawn -> execute -> collect results -> purge

    Tracks active subagents and their completion status.
    Provides get_results() to collect all slice outputs.
    """

    def __init__(self, python_executable: Optional[str] = None):
        self.engine = SubagentEngine(python_executable=python_executable)
        self._results: Dict[str, SubagentResult] = {}
        self._active: Dict[str, bool] = {}
        self._order: List[str] = []

    def spawn(self, spec: SubagentSpec) -> SubagentResult:
        """
        Spawn a subagent for a vertical slice.
        Executes synchronously (blocking), then purges context.
        """
        module_name = spec.module_name
        self._active[module_name] = True
        self._order.append(module_name)

        result = self.engine.spawn(spec)
        self._results[module_name] = result
        self._active[module_name] = False

        return result

    def spawn_all(self, specs: List[SubagentSpec]) -> Dict[str, SubagentResult]:
        """
        Spawn all subagents sequentially.
        Each runs in isolation; context is purged between slices.
        """
        for spec in specs:
            self.spawn(spec)
        return self._results

    def get_results(self) -> Dict[str, SubagentResult]:
        """Return all collected results keyed by module_name."""
        return dict(self._results)

    def get_ordered_results(self) -> List[SubagentResult]:
        """Return results in spawn order."""
        return [self._results[m] for m in self._order if m in self._results]

    def get_summary(self) -> Dict[str, Any]:
        """Return a summary report of all subagent executions."""
        total = len(self._results)
        success = sum(1 for r in self._results.values() if r.status == "success")
        failed = sum(1 for r in self._results.values() if r.status == "failed")
        errors = sum(1 for r in self._results.values() if r.status == "error")
        total_files = sum(len(r.files_created) for r in self._results.values())
        total_duration = sum(r.duration_ms for r in self._results.values())

        return {
            "total_modules": total,
            "success": success,
            "failed": failed,
            "errors": errors,
            "total_files_created": total_files,
            "total_duration_ms": round(total_duration, 2),
            "status": "APROVADO" if (failed == 0 and errors == 0) else "REPROVADO",
            "modules": {
                name: {
                    "status": r.status,
                    "files_created": len(r.files_created),
                    "errors": r.errors,
                    "duration_ms": round(r.duration_ms, 2),
                }
                for name, r in self._results.items()
            },
        }

    def is_active(self) -> bool:
        """Check if any subagent is currently running."""
        return any(self._active.values())

    @property
    def active_count(self) -> int:
        """Number of currently active subagents."""
        return sum(1 for v in self._active.values() if v)

    @property
    def completed_count(self) -> int:
        """Number of completed subagents."""
        return len(self._results)
