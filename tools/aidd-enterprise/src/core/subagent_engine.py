@dataclass
class SubagentSpec:
    """Specification for a single vertical-slice subagent."""
    module_name: str
    spec_text: str  # The slice SPEC (~1200 tokens max)
    prompt_template: str = ""
    target_dir: str = "."
    extra_args: Dict[str, Any] = field(default_factory=dict)

    def __post_init__(self):
        if not self.prompt_template:
            self.prompt_template = (
                "You are an AIDD vertical-slice builder. "
                "Generate the complete module '{module_name}' following the SPEC below. "
                "Write all files to disk under the target directory. "
                "Return a JSON result with keys: module_name, status, files_created, errors.\n\n"
                "## SPEC\n{spec_text}\n\n"
                "## Target Directory\n{target_dir}\n"
            )

    def render_prompt(self) -> str:
        return self.prompt_template.format(
            module_name=self.module_name,
            spec_text=self.spec_text,
            target_dir=self.target_dir,
        )


@dataclass
class SubagentResult:
    """Result returned by a completed subagent."""
    module_name: str
    status: str  # "success", "failed", "error"
    files_created: List[str] = field(default_factory=list)
    errors: List[str] = field(default_factory=list)
    duration_ms: float = 0.0
    exit_code: int = -1
    stdout: str = ""
    stderr: str = ""


