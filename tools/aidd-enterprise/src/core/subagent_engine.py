class SubagentEngine:
    """
    Spawns individual subagents as isolated subprocesses.
    Each subagent receives only its slice's SPEC and writes files to disk.
    Results are read back from a JSON manifest on disk.
    """

    def __init__(self, python_executable: Optional[str] = None):
        self.python = python_executable or sys.executable

    def spawn(self, spec: SubagentSpec) -> SubagentResult:
        """
        Launch a subagent for one vertical slice.
        The subagent runs as a subprocess with a minimal prompt.
        After completion, its result is read from disk and the manifest is purged.
        """
        module_name = spec.module_name
        target_dir = os.path.abspath(spec.target_dir)
        result_path = os.path.join(target_dir, ".subagent_result_" + module_name + ".json")

        # Build worker script from template
        worker_code = (
            _WORKER_TEMPLATE
            .replace("__MODULE_NAME__", module_name)
            .replace("__TARGET_DIR__", target_dir)
            .replace("__RESULT_PATH__", result_path)
        )

        # Write worker to a temp file
        fd, script_path = tempfile.mkstemp(suffix=".py", prefix="aidd_subagent_")
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as fh:
                fh.write(worker_code)

            t0 = time.time()
            try:
                proc = subprocess.run(
                    [self.python, script_path],
                    cwd=target_dir,
                    capture_output=True,
                    text=True,
                    timeout=300,
                    errors="replace",
                )
                duration_ms = (time.time() - t0) * 1000

                result = self._read_result(result_path, module_name)
                result.duration_ms = duration_ms
                result.exit_code = proc.returncode
                result.stdout = proc.stdout[-2000:] if proc.stdout else ""
                result.stderr = proc.stderr[-2000:] if proc.stderr else ""

                if proc.returncode != 0 and result.status == "success":
                    result.status = "failed"
                    if not result.errors:
                        result.errors = ["Process exited with code " + str(proc.returncode)]

                return result

            except subprocess.TimeoutExpired:
                return SubagentResult(
                    module_name=module_name,
                    status="error",
                    errors=["Subagent timed out after 300s"],
                    duration_ms=(time.time() - t0) * 1000,
                    exit_code=-1,
                )
            except Exception as e:
                return SubagentResult(
                    module_name=module_name,
                    status="error",
                    errors=[str(e)],
                    duration_ms=(time.time() - t0) * 1000,
                    exit_code=-1,
                )
            finally:
                # Purge: remove result manifest and temp script
                self._purge_artifact(result_path)
        finally:
            self._purge_artifact(script_path)

    def _read_result(self, result_path: str, module_name: str) -> SubagentResult:
        """Read the subagent result manifest from disk."""
        if not os.path.exists(result_path):
            return SubagentResult(
                module_name=module_name,
                status="error",
                errors=["Result manifest not found on disk"],
            )
        try:
            with open(result_path, "r", encoding="utf-8") as f:
                data = json.load(f)
            return SubagentResult(
                module_name=data.get("module_name", module_name),
                status=data.get("status", "error"),
                files_created=data.get("files_created", []),
                errors=data.get("errors", []),
            )
        except Exception as e:
            return SubagentResult(
                module_name=module_name,
                status="error",
                errors=["Failed to parse result manifest: " + str(e)],
            )

    @staticmethod
    def _purge_artifact(path: str):
        """Remove an artifact file (context purge)."""
        try:
            if os.path.exists(path):
                os.remove(path)
        except OSError:
            pass  # Best-effort purge


